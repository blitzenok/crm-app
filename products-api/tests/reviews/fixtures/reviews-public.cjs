  /* --- the product card: the block of approved reviews --- */
  function buildBlock(doc, list) {
    var wrap = el(doc, 'section', 'brv-wrap');
    wrap.id = 'blr-reviews';
    wrap.setAttribute('aria-labelledby', 'blr-reviews-title');
    var h = el(doc, 'h2', '', TEXT.heading);
    h.id = 'blr-reviews-title';
    wrap.appendChild(h);
    var i, r, item, head;
    for (i = 0; i < list.length; i++) {
      r = list[i];
      item = el(doc, 'div', 'brv-item');
      head = el(doc, 'div', 'brv-head');
      head.appendChild(el(doc, 'span', 'brv-name', r.displayName));
      head.appendChild(el(doc, 'span', 'brv-badge', TEXT.verified));
      var when = formatMonth(r.date);
      if (when) head.appendChild(el(doc, 'span', 'brv-date', when));
      item.appendChild(head);
      item.appendChild(el(doc, 'p', 'brv-text', r.text));
      wrap.appendChild(item);
    }
    wrap.appendChild(el(doc, 'p', 'brv-note', TEXT.note));
    return wrap;
  }
  /* Before the "pairs well" rail (right after the FAQ); else the end of <main>; else before the footer. Returns false when there is no place yet. */
  function placeBlock(doc, block) {
    var rail = doc.getElementById('productRail');
    if (rail && rail.parentNode) { rail.parentNode.insertBefore(block, rail); return true; }
    var main = doc.getElementById('main');
    if (main) { main.appendChild(block); return true; }
    var foot = doc.getElementById('site-footer');
    if (foot && foot.parentNode) { foot.parentNode.insertBefore(block, foot); return true; }
    return false;
  }
  function mountWidget(doc, win, slug) {
    var fetchFn = win.fetch;
    if (typeof fetchFn !== 'function') return;
    fetchFn.call(win, '/api/reviews?slug=' + encodeURIComponent(slug), { credentials: 'same-origin' })
      .then(function (r) { return r.ok ? r.json() : null; })
      .then(function (j) {
        var parsed = parseReviews(j), flag = '';
        try { flag = win.localStorage.getItem('blr_reviews_preview') || ''; } catch (e) { flag = ''; }
        if (!shouldShow(parsed, flag)) return;
        css(doc);
        var block = buildBlock(doc, parsed.reviews);
        var tries = 0;
        (function attach() {
          if (placeBlock(doc, block)) return;
          if (++tries < 6) win.setTimeout(attach, 500);
        })();
      })
      .catch(function () { /* no answer: nothing is drawn */ });
  }

  /* --- the /review page --- */
  function request(win, method, url, body) {
    var init = { method: method, credentials: 'same-origin' };
    if (body !== undefined) { init.headers = { 'Content-Type': 'application/json' }; init.body = JSON.stringify(body); }
    return win.fetch(url, init).then(function (r) {
      return r.json().then(function (j) { return { status: r.status, json: j }; }, function () { return { status: r.status, json: null }; });
    }, function () { return { status: 0, json: null }; });
  }
  function say(node, kind, text) {
    node.className = 'brv-msg' + (kind ? ' ' + kind : '');
    node.textContent = text || '';
  }

  function buildRating(doc, win, link, data, app) {
    var card = el(doc, 'div', 'brv-card');
    var existing = data.rating || null;
    var locked = !!(existing && existing.locked);
    var chosen = link.r || (existing ? existing.r : 0);
    var group = el(doc, 'div', 'brv-stars');
    group.setAttribute('role', 'radiogroup');
    group.setAttribute('aria-label', 'Rating from 1 to 5');
    var buttons = [], i;
    function paint() {
      for (i = 0; i < buttons.length; i++) {
        var on = i + 1 <= chosen;
        buttons[i].className = 'brv-star' + (on ? ' on' : '');
        buttons[i].setAttribute('aria-checked', chosen === i + 1 ? 'true' : 'false');
      }
    }
    function pick(n) { return function () { if (locked) return; chosen = n; paint(); }; }
    for (i = 0; i < 5; i++) {
      var b = el(doc, 'button', 'brv-star', STAR);
      b.setAttribute('type', 'button');
      b.setAttribute('role', 'radio');
      b.setAttribute('aria-label', (i + 1) + (i === 0 ? ' star' : ' stars'));
      if (locked) b.setAttribute('disabled', 'disabled');
      b.addEventListener('click', pick(i + 1));
      buttons.push(b);
      group.appendChild(b);
    }
    paint();
    card.appendChild(group);
    var label = el(doc, 'label', 'brv-label', TEXT.commentLabel);
    label.setAttribute('for', 'brv-comment');
    var area = el(doc, 'textarea', 'brv-area');
    area.id = 'brv-comment';
    area.setAttribute('maxlength', '1000');
    area.value = existing ? existing.comment || '' : '';
    if (locked) area.setAttribute('disabled', 'disabled');
    var msg = el(doc, 'p', 'brv-msg');
    msg.setAttribute('role', 'status');
    card.appendChild(label);
    card.appendChild(area);
    if (locked) {
      say(msg, 'ok', TEXT.ratingLocked);
    } else {
      var send = el(doc, 'button', 'brv-btn', existing ? TEXT.updateRating : TEXT.sendRating);
      send.setAttribute('type', 'button');
      var busy = false;
      send.addEventListener('click', function () {
        if (busy) return;
        if (!chosen) { say(msg, 'err', TEXT.pickStar); return; }
        busy = true; send.setAttribute('disabled', 'disabled'); say(msg, '', TEXT.sending);
        request(win, 'POST', '/api/review/rating', ratingPayload(link, chosen, area.value)).then(function (res) {
          busy = false; send.removeAttribute('disabled');
          if (res.status === 200 && res.json && res.json.ok === true) { send.textContent = TEXT.updateRating; say(msg, 'ok', TEXT.ratingSaved); }
          else if (res.status === 409) say(msg, 'err', TEXT.locked);
          else say(msg, 'err', replyText(res.status, res.json && res.json.error));
        });
      });
      var row = el(doc, 'div', 'brv-row');
      row.appendChild(send);
      card.appendChild(row);
    }
    card.appendChild(msg);
    return card;
  }

  function buildProduct(doc, win, link, data, item, done) {
    var card = el(doc, 'div', 'brv-card');
    var top = el(doc, 'div', 'brv-prod');
    top.appendChild(el(doc, 'b', '', item.name));
    var slot = el(doc, 'span', '');
    top.appendChild(slot);
    card.appendChild(top);
    var formBox = el(doc, 'div', '');
    card.appendChild(formBox);
    function sentState() { clear(slot); slot.appendChild(el(doc, 'span', 'brv-badge', TEXT.alreadySent)); clear(formBox); }
    if (done[item.slug]) { sentState(); return card; }
    var open = el(doc, 'button', 'brv-btn ghost', TEXT.writeReview);
    open.setAttribute('type', 'button');
    slot.appendChild(open);
    function showForm() {
      clear(formBox);
      var lab = el(doc, 'label', 'brv-label', TEXT.reviewLabel);
      var area = el(doc, 'textarea', 'brv-area');
      area.id = 'brv-text-' + item.slug;
      lab.setAttribute('for', area.id);
      area.setAttribute('maxlength', '1000');
      var count = el(doc, 'p', 'brv-count', '0 / 1000');
      area.addEventListener('input', function () { count.textContent = String(area.value.length) + ' / 1000'; });
      var nlab = el(doc, 'label', 'brv-label', TEXT.nameLabel);
      var name = el(doc, 'input', 'brv-input');
      name.id = 'brv-name-' + item.slug;
      nlab.setAttribute('for', name.id);
      name.setAttribute('type', 'text');
      name.setAttribute('maxlength', '30');
      name.value = data.defaultName || '';
      var checkRow = el(doc, 'label', 'brv-check');
      var box = el(doc, 'input', '');
      box.setAttribute('type', 'checkbox');
      checkRow.appendChild(box);
      checkRow.appendChild(el(doc, 'span', '', TEXT.consent));
      var ruo = el(doc, 'p', 'brv-muted', TEXT.reviewRuo);
      var hint = el(doc, 'p', 'brv-muted', TEXT.reviewHint);
      var msg = el(doc, 'p', 'brv-msg');
      msg.setAttribute('role', 'status');
      var go = el(doc, 'button', 'brv-btn', TEXT.submit);
      go.setAttribute('type', 'button');
      var cancel = el(doc, 'button', 'brv-btn ghost', TEXT.cancel);
      cancel.setAttribute('type', 'button');
      cancel.addEventListener('click', function () { clear(formBox); slot.appendChild(open); });
      var busy = false;
      go.addEventListener('click', function () {
        if (busy) return;
        var v = checkReview({ text: area.value, name: name.value, consent: !!box.checked });
        if (!v.ok) { say(msg, 'err', v.error); return; }
        busy = true; go.setAttribute('disabled', 'disabled'); say(msg, '', TEXT.sending);
        request(win, 'POST', '/api/review/submit', reviewPayload(link, item.slug, v)).then(function (res) {
          busy = false; go.removeAttribute('disabled');
          if (res.status === 200 && res.json && res.json.ok === true) { done[item.slug] = true; sentState(); formBox.appendChild(el(doc, 'p', 'brv-msg ok', TEXT.reviewSent)); }
          else if (res.status === 409) { done[item.slug] = true; sentState(); formBox.appendChild(el(doc, 'p', 'brv-msg', replyText(409, res.json && res.json.error))); }
          else say(msg, 'err', replyText(res.status, res.json && res.json.error));
        });
      });
      var row = el(doc, 'div', 'brv-row');
      row.appendChild(go); row.appendChild(cancel);
      [lab, area, count, nlab, name, checkRow, ruo, hint, row, msg].forEach(function (n) { formBox.appendChild(n); });
      try { area.focus(); } catch (e) { /* ignore */ }
    }
    open.addEventListener('click', function () { if (open.parentNode === slot) slot.removeChild(open); showForm(); });
    return card;
  }

  function mountPage(doc, win) {
    var app = doc.getElementById('review-app');
    if (!app) return;
    css(doc);
    var link = parseLink(win.location.hash);
    function fail(text) { clear(app); app.appendChild(el(doc, 'p', '', text)); }
    if (!link.o || !link.t) { fail(TEXT.invalid); return; }
    clear(app);
    app.appendChild(el(doc, 'p', 'brv-muted', TEXT.loading));
    request(win, 'POST', '/api/review/order', { o: link.o, t: link.t }).then(function (res) {
      if (res.status === 404) { fail(TEXT.invalid); return; }
      if (res.status === 429) { fail(TEXT.busy); return; }
      var d = res.json;
      if (res.status !== 200 || !d || typeof d.orderNumber !== 'string' || !Array.isArray(d.items)) { fail(TEXT.unavailable); return; }
      clear(app);
      app.appendChild(el(doc, 'h1', '', TEXT.askPrefix + d.orderNumber + TEXT.askSuffix));
      if (d.firstName) app.appendChild(el(doc, 'p', '', 'Hi ' + d.firstName + ', thank you for your order.'));
      app.appendChild(buildRating(doc, win, link, d, app));
      app.appendChild(el(doc, 'p', 'brv-muted', TEXT.privateNote));
      if (d.items.length) {
        app.appendChild(el(doc, 'h2', '', TEXT.reviewHeading));
        app.appendChild(el(doc, 'p', 'brv-muted', TEXT.reviewRuo));
        var done = {}, i;
        for (i = 0; i < (d.reviewed || []).length; i++) done[d.reviewed[i]] = true;
        for (i = 0; i < d.items.length; i++) {
          if (d.items[i] && typeof d.items[i].slug === 'string' && typeof d.items[i].name === 'string') app.appendChild(buildProduct(doc, win, link, d, d.items[i], done));
        }
      }
    });
  }

