  /* The link of the letter: the fragment #o=<order number>&t=<token>[&r=1..5] (location.hash). Only the fragment is read: the letters that carry this form are
     the only ones there are. Anything that does not have the shape of one is dropped. */
  function parseLink(hash) {
    var out = { o: '', t: '', r: 0 };
    var s = typeof hash === 'string' && hash.charAt(0) === '#' ? hash.slice(1) : '';   /* only a fragment counts: a query is not a link */
    var parts = s ? s.split('&') : [], i, kv, k, v;
    for (i = 0; i < parts.length; i++) {
      kv = parts[i].split('=');
      k = kv[0];
      try { v = decodeURIComponent((kv.slice(1).join('=') || '').replace(/\+/g, ' ')); } catch (e) { v = ''; }
      if (k === 'o' && /^[A-Za-z0-9._-]{1,64}$/.test(v)) out.o = v;
      else if (k === 't' && /^[A-Za-z0-9_-]{32}$/.test(v)) out.t = v;
      else if (k === 'r' && /^[1-5]$/.test(v)) out.r = Number(v);
    }
    return out;
  }
  /* "2026-10" (what the server sends; a full date is read too) -> "October 2026". A month, not a day: less to correlate with an order. */
  function formatMonth(iso) {
    var m = /^(\d{4})-(\d{2})(?:-\d{2})?$/.exec(String(iso || ''));
    if (!m) return '';
    var n = Number(m[2]);
    return n >= 1 && n <= 12 ? MONTHS[n - 1] + ' ' + m[1] : '';
  }
  /* The answer of GET /api/reviews: only a well-formed list is trusted; preview true = test mode, shown only to a browser that opted in. */
  function parseReviews(json) {
    if (!json || typeof json !== 'object' || !Array.isArray(json.reviews)) return null;
    var list = [], i, r;
    for (i = 0; i < json.reviews.length; i++) {
      r = json.reviews[i];
      if (r && typeof r.text === 'string' && r.text && typeof r.displayName === 'string') list.push({ displayName: r.displayName, text: r.text, date: typeof r.date === 'string' ? r.date : '' });
    }
    return { reviews: list, preview: json.preview === true };
  }
  function shouldShow(parsed, previewFlag) {
    if (!parsed || !parsed.reviews.length) return false;
    if (parsed.preview && previewFlag !== '1') return false;
    return true;
  }
  function checkReview(v) {
    var text = String(v && v.text || '').replace(/^\s+|\s+$/g, '');
    if (text.length < 20) return { ok: false, error: TEXT.tooShort };
    if (text.length > 1000) return { ok: false, error: TEXT.tooLong };
    var name = String(v && v.name || '').replace(/\s+/g, ' ').replace(/^\s+|\s+$/g, '');
    if (name.length < 2 || name.length > 30 || /[@<>\/\\0-9]/.test(name)) return { ok: false, error: TEXT.badName };
    if (v.consent !== true) return { ok: false, error: TEXT.needConsent };
    return { ok: true, text: text, name: name };
  }
  function ratingPayload(link, r, comment) {
    return { o: link.o, t: link.t, r: r, comment: String(comment || '').replace(/^\s+|\s+$/g, '') };
  }
  function reviewPayload(link, slug, v) {
    return { o: link.o, t: link.t, slug: slug, text: v.text, displayName: v.name, consent: true };
  }
  /* The words under a form for each outcome; a 400 carries the server's own sentence. */
  function replyText(status, serverError) {
    if (status === 404) return TEXT.invalid;
    if (status === 429) return TEXT.busy;
    if (status === 409) return serverError ? String(serverError) : TEXT.duplicate;
    if (status === 400 && serverError) return String(serverError);
    return TEXT.fail;
  }

